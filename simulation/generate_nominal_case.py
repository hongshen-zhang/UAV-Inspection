def project_lonlat(lon: float, lat: float) -> np.ndarray:
    lon0, lat0 = BASE_LONLAT
    return np.array(
        [
            math.radians(float(lon) - lon0) * EARTH_R_M * math.cos(math.radians(lat0)),
            math.radians(float(lat) - lat0) * EARTH_R_M,
        ],
        dtype=float,
    )

def channel_rows(task_xy: np.ndarray, mec_xy: np.ndarray, phys: dict, task_id: int) -> list[dict]:
    """Recompute paper communication quantities from the Figure 4 geometry."""
    n0 = float(phys["noise_psd_w_hz"]) * 10.0 ** (float(phys.get("noise_figure_db", 0.0)) / 10.0)
    rows = []
    for mec_id, server_xy in enumerate(mec_xy, start=1):
        horizontal = float(np.linalg.norm(task_xy - server_xy))
        h = math.hypot(horizontal, float(phys["uav_altitude_m"]))
        theta = math.degrees(math.asin(float(phys["uav_altitude_m"]) / h))
        p_los = 1.0 / (1.0 + float(phys["los_a"]) * math.exp(-float(phys["los_b"]) * (theta - float(phys["los_a"]))))
        fs_db = 20.0 * math.log10(4.0 * math.pi * float(phys["fc_hz"]) * h / 299_792_458.0)
        path_loss = fs_db + p_los * float(phys["eta_los_db"]) + (1.0 - p_los) * float(phys["eta_nlos_db"])
        gain = 10.0 ** (-path_loss / 10.0)
        ul_snr = float(phys["tx_power_w"]) * gain / (n0 * float(phys["ul_bw_hz"]))
        dl_snr = float(phys["mec_tx_power_w"]) * gain / (n0 * float(phys["dl_bw_hz"]))
        ul = float(phys["ul_bw_hz"]) * math.log2(1.0 + max(ul_snr, 0.0)) / 1e6
        dl = float(phys["dl_bw_hz"]) * math.log2(1.0 + max(dl_snr, 0.0)) / 1e6
        ul_ok, dl_ok = ul >= float(phys["ul_min_mbps"]), dl >= float(phys["dl_min_mbps"])
        rows.append({
            "task_id": task_id,
            "mec_id": mec_id,
            "distance_m": horizontal,
            "link_distance_3d_m": h,
            "elevation_deg": theta,
            "los_probability": p_los,
            "los_state": "average_los_nlos",
            "free_space_path_loss_db": fs_db,
            "path_loss_offset_db": 0.0,
            "path_loss_db": path_loss,
            "channel_gain": gain,
            "ul_rate_mbps": ul,
            "dl_rate_mbps": dl,
            "ul_available": int(ul_ok),
            "dl_available": int(dl_ok),
            "mec_available": int(ul_ok and dl_ok),
        })
    return rows

def write_csv(path, rows, fields=None):
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields or list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def generate(output, seed_start=2026092000, seed_count=300):
    if seed_count < 1:
        raise ValueError("seed_count must be positive")
    output = Path(output)
    if output.resolve() == Path(__file__).resolve().with_name("nominal_case"):
        raise ValueError("Choose a new output directory to preserve the frozen inputs")
    output.mkdir(parents=True, exist_ok=True)
    config = copy.deepcopy(CONFIG)
    task_rows, summaries = [], []
    for seed in range(seed_start, seed_start + seed_count):
        one = []
        for template in TASK_ATTRIBUTES:
            row = dict(template)
            task_id = int(row["task_id"])
            mean, sigma = float(row["mean_workload_gcy"]), float(row["sigma"])
            mu = math.log(mean) - 0.5 * sigma * sigma
            rng = np.random.default_rng(np.random.SeedSequence([seed, task_id, 20260911]))
            workload = math.exp(mu + sigma * float(rng.standard_normal()))
            xy = project_lonlat(float(row["lon"]), float(row["lat"]))
            row.update(case_id="nominal", seed=str(seed),
                       x_m=f"{xy[0]:.12f}", y_m=f"{xy[1]:.12f}",
                       mu=f"{mu:.17g}", workload_gcy=f"{workload:.17g}")
            one.append(row)
            task_rows.append(row)
        digest = hashlib.sha256(json.dumps(one, sort_keys=True).encode()).hexdigest()
        summaries.append(dict(seed=seed, mission_fingerprint=digest))
    mecs = sorted((n for n in NODES if n["node_type"] == "mec"),
                  key=lambda n: int(n["mec_id"]))
    mec_xy = np.asarray([project_lonlat(float(n["lon"]), float(n["lat"])) for n in mecs])
    links = []
    for task in TASK_ATTRIBUTES:
        xy = project_lonlat(float(task["lon"]), float(task["lat"]))
        links.extend(channel_rows(xy, mec_xy, config["physics"], int(task["task_id"])))
    fields = ["case_id", "seed", "task_id", "lon", "lat", "x_m", "y_m", "region",
              "data_mbit", "output_ratio", "deadline_s", "weight", "mu", "sigma",
              "mean_workload_gcy", "workload_gcy"]
    write_csv(output / "tasks.csv", task_rows, fields)
    write_csv(output / "nodes.csv", NODES)
    write_csv(output / "links.csv", links)
    write_csv(output / "mission_summary.csv", summaries)
    (output / "config.json").write_text(json.dumps(config, indent=2) + "\n")
    return output


